import { readFile, readdir, lstat } from 'node:fs/promises';
import { resolve } from 'node:path';
import Ajv from 'ajv';

// Same build-time trust boundary as the library: reviewed JSON compiles to inert data.
export async function collectionArtifacts(root) {
  const directory = resolve(root, 'collections');
  const fail = message => { throw new Error('Invalid collections: ' + message); };
  const regular = async (path, directory = false) => {
    const stat = await lstat(path);
    if (stat.isSymbolicLink() || !(directory ? stat.isDirectory() : stat.isFile())) fail('symlink or unexpected file type');
  };
  await regular(directory, true);
  await regular(resolve(directory, 'collection.schema.json'));
  const schema = JSON.parse(await readFile(resolve(directory, 'collection.schema.json')));
  const validate = new Ajv({ allErrors: true, strict: false }).compile(schema);
  const definitions = [];
  for (const name of (await readdir(directory)).sort()) {
    if (['README.md', 'collection.schema.json'].includes(name)) { await regular(resolve(directory,name)); continue; }
    if (!/^[a-z][a-z0-9-]*$/.test(name)) fail('unsafe ID');
    const path = resolve(directory,name);
    await regular(path,true);
    const files = await readdir(path);
    if (files.length !== 1 || files[0] !== 'collection.json') fail('unexpected file');
    await regular(resolve(path,'collection.json'));
    const definition = JSON.parse(await readFile(resolve(path,'collection.json')));
    if (!validate(definition)) fail(new Ajv().errorsText(validate.errors));
    if (definition.id !== name || ['editors','_superusers'].includes(name)) fail('identity');
    const fields = definition.fields;
    if (new Set(fields.map(f => f.name)).size !== fields.length || fields.some(f => ['id','__proto__','constructor','prototype','length','item','namedItem'].includes(f.name))) fail('duplicate or reserved field');
    if (!fields.some(f => f.name === definition.editorRecordLabel && f.type === 'text')) fail('record label');
    for (const rule of Object.values(definition.publicReadRules))
      if (!fields.some(f => f.name === rule.split(' ')[0] && f.type === 'bool')) fail('public rule requires boolean field');
    for (const name of Object.values(definition.publicDisplay))
      if (!fields.some(f => f.name === name && f.type === 'text')) fail('public display requires text field');
    definitions.push(definition);
  }
  definitions.sort((a,b) => a.order - b.order);
  if (!definitions.length || new Set(definitions.map(d => d.order)).size !== definitions.length) fail('missing collections or duplicate order');
  const collections = Object.fromEntries(definitions.map(d => [d.id,d]));
  return { collections, data: '// Generated by the library compiler; inert collection data.\nexport const collections = ' + JSON.stringify(collections,null,2) + ' as const;\n' };
}
