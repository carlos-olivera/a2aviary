import { readFile, readdir, lstat } from 'node:fs/promises';
import { resolve } from 'node:path';
import Ajv from 'ajv';
import { canonicalJson, generateContracts, validateLibrarySelection } from '@a2aviary/site-core';

export async function starterArtifacts(root, policy, catalog) {
  const dir = resolve(root, 'starters');
  const fail = message => { throw Error('Invalid starters: ' + message); };
  const regular = async (path, directory = false) => {
    const stat = await lstat(path);
    if (stat.isSymbolicLink() || !(directory ? stat.isDirectory() : stat.isFile())) fail('symlink or unexpected file type');
  };
  await regular(dir, true);
  await regular(resolve(dir,'starter.schema.json'));
  const ajv = new Ajv({ allErrors: true, strict: false });
  const validate = ajv.compile(JSON.parse(await readFile(resolve(dir,'starter.schema.json'))));
  const partial = structuredClone(generateContracts(policy).siteSchema);
  function optional(v) {
    if (!v || typeof v !== 'object') return;
    delete v.required; delete v.minItems;
    for (const c of Object.values(v)) Array.isArray(c) ? c.forEach(optional) : optional(c);
  }
  optional(partial);
  ajv.addFormat('site-link', () => false); // seeds contain no URLs or copy
  const validateSeed = ajv.compile(partial), definitions = [];
  const unique = values => { if (new Set(values).size !== values.length) fail('duplicate IDs'); };
  for (const id of (await readdir(dir)).sort()) {
    if (['README.md','starter.schema.json'].includes(id)) { await regular(resolve(dir,id)); continue; }
    if (id === 'snapshots') { await regular(resolve(dir,id),true); continue; }
    if (!/^[a-z][a-z0-9-]{0,63}$/.test(id)) fail('unsafe ID');
    await regular(resolve(dir,id),true);
    for (const version of (await readdir(resolve(dir,id))).sort()) {
      if (!/^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$/.test(version)) fail('invalid version');
      const path = resolve(dir,id,version);
      await regular(path,true);
      if (canonicalJson(await readdir(path)) !== '["starter.json"]') fail('unexpected file');
      await regular(resolve(path,'starter.json'));
      const d = JSON.parse(await readFile(resolve(path,'starter.json')));
      if (!validate(d)) fail(ajv.errorsText(validate.errors));
      if (d.id !== id || d.version !== version) fail('identity');
      await regular(resolve(dir,'snapshots',id),true);
      const snapshot = resolve(dir,'snapshots',id,version + '.json');
      await regular(snapshot);
      if (canonicalJson(d) !== canonicalJson(JSON.parse(await readFile(snapshot)))) fail('frozen version changed; publish a new version');
      const seed = {pages:d.seed.pages,assets:[]};
      if (!validateSeed(seed)) fail('seed plan/schema: ' + ajv.errorsText(validateSeed.errors));
      unique(d.inputs.map(i => i.id)); unique(seed.pages.map(p => p.id));
      for (const p of seed.pages) {
        unique(p.sections.map(s => s.id));
        const blocks = p.sections.flatMap(s => s.blocks);
        unique(blocks.map(b => b.id));
        if (blocks.length > policy.firstVersion.structure.maxBlocksPerPage.value) fail('seed block limit');
      }
      const selections = [seed, ...(d.suggestions ?? []).map(s => ({pages:[{sections:[{blocks:[{component:s.component,variant:s.variant,props:{}}]}]}]}))];
      let experimental = false;
      for (const spec of selections) {
        const errors = validateLibrarySelection(spec,policy,catalog,{test:true}).filter(e => e.rule !== 'content.required');
        if (errors.length) fail('package compatibility/budget: ' + JSON.stringify(errors));
        if (validateLibrarySelection(spec,policy,catalog,{test:false}).some(e => e.rule === 'library.status')) experimental = true;
      }
      if (experimental && d.status === 'stable') fail('experimental packages require an experimental starter');
      definitions.push(d);
    }
  }
  if (!definitions.length) fail('empty registry');
  return '// Generated by the library compiler; inert starter data.\nimport type { Starter } from \'./starters.ts\';\nexport const starters: readonly Starter[] = ' + JSON.stringify(definitions,null,2) + ';\n';
}
